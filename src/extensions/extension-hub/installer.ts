/**
 * Filesystem side of installing and removing extensions.
 *
 * A tree is extracted from the mirror into a staging folder below the hub's
 * work directory, checked, and then renamed into the external extensions
 * directory in one step. Loading and unloading is left to the extension
 * directory watcher; the hub waits for the registry to report the outcome.
 *
 * @module
 */

import { existsSync } from "node:fs";
import { mkdir, mkdtemp, rename, rm } from "node:fs/promises";
import path from "node:path";
import type { ExternalExtensionsApi, ExternalFolderStatus } from "@ext/types";
import { HubError } from "./errors";
import { assertSafeRef, COMMIT_PATTERN, EXTENSION_NAME_PATTERN } from "./git";
import { type PackageMeta, parsePackageMeta, releaseTag } from "./packageMeta";
import type { SourceRepo } from "./sources";
import type { RefKind } from "./store";

/** Marker file written into every hub-installed extension (informational; the database is authoritative). */
export const SOURCE_MARKER = ".palim-source.json";

/** Files left out of the content hash: generated by the dependency resolver or by the hub. */
const HASH_IGNORED = new Set([SOURCE_MARKER, "tsconfig.json", "tsconfig.json.tmp", "bun.lock", "bun.lockb"]);

/** A resolved install target. */
export interface ResolvedTarget {
  /** Ref to record (tag name, branch name, or full SHA). */
  ref: string;
  /** How updates follow the ref. */
  refKind: RefKind;
  /** Commit to install. */
  commit: string;
}

/** A staged, verified tree ready to be moved into place. */
export interface StagedTree {
  /** Staging directory holding the extension files. */
  dir: string;
  /** package.json metadata. */
  meta: PackageMeta;
  /** Content hash of the tree. */
  contentHash: string;
}

/** Outcome of waiting for the registry. */
export type LoadOutcome =
  | { status: "loaded"; version: string }
  | { status: "failed"; error: string }
  | { status: "timeout" };

/**
 * Validates an extension name from a request.
 *
 * @param name - Candidate name
 * @returns The name
 * @throws {HubError} 400 when invalid
 */
export function assertExtensionName(name: string): string {
  if (!EXTENSION_NAME_PATTERN.test(name)) throw new HubError(400, `Invalid extension name "${name}"`);
  return name;
}

/**
 * Resolves what to install: an explicit version (release tag), an explicit
 * ref (tag, branch, or commit), or by default the given fallback.
 *
 * @param repo - Source mirror
 * @param name - Extension name
 * @param request - Requested version or ref
 * @param fallback - Target used when neither is given (null = none available)
 * @returns The target
 * @throws {HubError} 400 invalid input, 404 unknown version or ref
 */
export async function resolveTarget(
  repo: SourceRepo,
  name: string,
  request: { version?: string; ref?: string },
  fallback: ResolvedTarget | null,
): Promise<ResolvedTarget> {
  if (request.version !== undefined) {
    const tag = assertSafeRef(releaseTag(name, request.version));
    const commit = await repo.resolveCommit(`refs/tags/${tag}`);
    if (!commit) throw new HubError(404, `Version ${request.version} of "${name}" not found (no tag ${tag})`);
    return { ref: tag, refKind: "tag", commit };
  }
  if (request.ref !== undefined) {
    const ref = request.ref.trim();
    if (COMMIT_PATTERN.test(ref)) {
      const commit = await repo.resolveCommit(ref);
      if (commit) return { ref: commit, refKind: "commit", commit };
    }
    assertSafeRef(ref);
    const tagCommit = await repo.resolveCommit(`refs/tags/${ref}`);
    if (tagCommit) return { ref, refKind: "tag", commit: tagCommit };
    const branchCommit = await repo.resolveCommit(`refs/heads/${ref}`);
    if (branchCommit) return { ref, refKind: "branch", commit: branchCommit };
    throw new HubError(404, `Ref "${ref}" not found in the source`);
  }
  if (!fallback) throw new HubError(404, `"${name}" has no installable release or branch version`);
  return fallback;
}

/**
 * Extracts and verifies an extension tree into a fresh staging directory.
 *
 * @param repo - Source mirror
 * @param name - Extension folder name
 * @param target - Resolved target
 * @param stagingRoot - Parent directory for staging folders (same filesystem as the external directory)
 * @param sourceInfo - Data for the marker file
 * @returns The staged tree (the caller moves or removes it)
 * @throws {HubError} 422 when the tree is not installable
 */
export async function stageTree(
  repo: SourceRepo,
  name: string,
  target: ResolvedTarget,
  stagingRoot: string,
  sourceInfo: { sourceId: string; url: string },
): Promise<StagedTree> {
  const files = await repo.readFiles([`${target.commit}:${name}/index.ts`, `${target.commit}:${name}/package.json`]);
  if (files.get(`${target.commit}:${name}/index.ts`) == null) {
    throw new HubError(422, `"${name}/index.ts" does not exist at ${target.ref}`);
  }
  const parsed = parsePackageMeta(files.get(`${target.commit}:${name}/package.json`) ?? null, name);
  if (!parsed.ok) throw new HubError(422, `"${name}" at ${target.ref} is not installable: ${parsed.reason}`);

  await mkdir(stagingRoot, { recursive: true });
  const dir = await mkdtemp(path.join(stagingRoot, `${name}-`));
  try {
    await repo.extract(target.commit, name, dir);
    const contentHash = await hashTree(dir);
    await Bun.write(
      path.join(dir, SOURCE_MARKER),
      `${JSON.stringify(
        {
          note: "Installed by the Extension Hub. Local changes are detected and block updates.",
          source: sourceInfo.url,
          sourceId: sourceInfo.sourceId,
          ref: target.ref,
          commit: target.commit,
          version: parsed.meta.version,
        },
        null,
        2,
      )}\n`,
    );
    return { dir, meta: parsed.meta, contentHash };
  } catch (err) {
    await rm(dir, { recursive: true, force: true });
    throw err;
  }
}

/** Lists the hashed files of an extension tree (sorted, relative), skipping `node_modules` and generated files. */
async function listTreeFiles(root: string): Promise<string[]> {
  const glob = new Bun.Glob("**");
  const files: string[] = [];
  for await (const rel of glob.scan({ cwd: root, dot: true, onlyFiles: true, followSymlinks: false })) {
    const parts = rel.split(path.sep);
    if (parts.includes("node_modules") || parts[0] === ".git") continue;
    if (parts.length === 1 && HASH_IGNORED.has(rel)) continue;
    files.push(rel);
  }
  return files.sort();
}

/** Whether an error is a missing-file error (the file vanished between listing and reading). */
function isNotFound(err: unknown): boolean {
  return (err as NodeJS.ErrnoException)?.code === "ENOENT";
}

/**
 * Hashes the files of an extension tree (paths and contents), ignoring
 * `node_modules` and files generated after install. Files that vanish while
 * the tree is scanned are skipped.
 *
 * @param root - Extension directory
 * @returns Hex SHA-256
 */
export async function hashTree(root: string): Promise<string> {
  const hasher = new Bun.CryptoHasher("sha256");
  for (const rel of await listTreeFiles(root)) {
    let bytes: Uint8Array;
    try {
      bytes = await Bun.file(path.join(root, rel)).bytes();
    } catch (err) {
      if (isNotFound(err)) continue;
      throw err;
    }
    hasher.update(`${rel}\0`);
    hasher.update(bytes);
    hasher.update("\0");
  }
  return hasher.digest("hex");
}

/**
 * Cheap change detector for an extension tree: the same files as
 * {@link hashTree}, with their size, mtime, and inode instead of contents.
 * When it is unchanged, a previously computed {@link hashTree} still holds.
 *
 * @param root - Extension directory
 * @returns Opaque fingerprint
 */
export async function treeFingerprint(root: string): Promise<string> {
  const hasher = new Bun.CryptoHasher("sha256");
  for (const rel of await listTreeFiles(root)) {
    try {
      const stats = await Bun.file(path.join(root, rel)).stat();
      hasher.update(`${rel}\0${stats.size}\0${stats.mtimeMs}\0${stats.ino}\0`);
    } catch (err) {
      if (!isNotFound(err)) throw err;
    }
  }
  return hasher.digest("hex");
}

/**
 * Moves a directory to a unique name below a trash root (so the watcher sees
 * the extension disappear at once) and returns the new location.
 *
 * @param dir - Directory to move
 * @param trashRoot - Parent directory on the same filesystem
 * @returns The moved directory
 */
export async function moveAside(dir: string, trashRoot: string): Promise<string> {
  await mkdir(trashRoot, { recursive: true });
  const holder = await mkdtemp(path.join(trashRoot, `${path.basename(dir)}-`));
  const moved = path.join(holder, path.basename(dir));
  await rename(dir, moved);
  return moved;
}

/**
 * Moves a staged tree into the external extensions directory.
 *
 * @param staged - Staging directory
 * @param targetDir - Final extension directory (must not exist)
 * @throws {HubError} 409 when the target exists
 */
export async function placeTree(staged: string, targetDir: string): Promise<void> {
  if (existsSync(targetDir)) throw new HubError(409, `"${path.basename(targetDir)}" already exists`);
  await mkdir(path.dirname(targetDir), { recursive: true });
  await rename(staged, targetDir);
}

/** Options for {@link syncFolder}. */
export interface WaitOptions {
  /** Give up after this many ms. */
  timeoutMs: number;
}

/**
 * Asks the directory watcher to reconcile one extension folder and waits for
 * the registry's confirmed state of it.
 *
 * @param api - Registry view
 * @param folder - Folder name below the external extensions directory
 * @param options - Timeout
 * @returns The folder's state, or null when the watcher did not finish in time
 */
export async function syncFolder(
  api: ExternalExtensionsApi,
  folder: string,
  options: WaitOptions,
): Promise<ExternalFolderStatus | null> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  const timeout = new Promise<null>((resolve) => {
    timer = setTimeout(() => resolve(null), options.timeoutMs);
  });
  try {
    return await Promise.race([api.sync(folder), timeout]);
  } finally {
    clearTimeout(timer);
  }
}

/**
 * Interprets a folder's state after placing an extension there. Only an
 * active extension, or one the operator disabled earlier, counts as loaded.
 *
 * @param status - Result of {@link syncFolder}
 * @returns The load outcome
 */
export function loadOutcome(status: ExternalFolderStatus | null): LoadOutcome {
  if (!status) return { status: "timeout" };
  switch (status.status) {
    case "active":
      return { status: "loaded", version: status.version };
    case "suspended":
      if (!status.enabled && !status.error) return { status: "loaded", version: status.version };
      return { status: "failed", error: status.error ?? "the extension is not active" };
    case "failed":
      return { status: "failed", error: status.error };
    case "unloaded":
      return { status: "failed", error: "the extension was not loaded" };
  }
}
